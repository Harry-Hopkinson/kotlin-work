fun main() {
    // Create a variable called number equal to 5.
    var number = 5;
    println("Number is equal to: " + number);

    // Reassign the value of the variable
    number = 10;
    println("Number is now equal to: " + number);

    // Create a variable that can't change value
    val pi = 3.14159;
    println("Pi is equal to: " + pi);
}